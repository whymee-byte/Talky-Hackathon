"""Profile the hackathon data at scale (duckdb, no row loops).

Usage:  .venv/bin/python explore/profile.py            # writes explore/PROFILE.md
Caches raw CSVs as Parquet in data_cache/<phase>/<table>.parquet (git-ignored).
"""
import os
import time

import duckdb

ROOT = "data/bankrec-docs-and-masters"
CACHE = "data_cache"
PHASES = ["sample", "train", "live"]
TABLES = ["bank_transactions", "ar_invoices", "ap_invoices", "credit_notes",
          "golden_allocations", "open_items_at_start"]

con = duckdb.connect()
con.execute("SET preserve_insertion_order=false")
out = []


def p(s=""):
    out.append(s)


def md(sql, title=None, limit=40):
    df = con.execute(sql).df()
    if title:
        p(f"**{title}**\n")
    p(df.head(limit).to_markdown(index=False))
    p()
    return df


def cache():
    for ph in PHASES:
        os.makedirs(f"{CACHE}/{ph}", exist_ok=True)
        for t in TABLES:
            src = f"{ROOT}/{ph}/{t}.csv.gz"
            dst = f"{CACHE}/{ph}/{t}.parquet"
            if os.path.exists(src) and not os.path.exists(dst):
                con.execute(f"COPY (SELECT * FROM read_csv('{src}', all_varchar=false, sample_size=-1)) "
                            f"TO '{dst}' (FORMAT parquet)")
    for f in os.listdir(f"{ROOT}/masters"):
        if f.endswith(".csv"):
            dst = f"{CACHE}/masters/{f[:-4]}.parquet"
            os.makedirs(f"{CACHE}/masters", exist_ok=True)
            if not os.path.exists(dst):
                con.execute(f"COPY (SELECT * FROM read_csv('{ROOT}/masters/{f}', sample_size=-1)) "
                            f"TO '{dst}' (FORMAT parquet)")


def view(ph, t):
    return f"'{CACHE}/{ph}/{t}.parquet'"


t0 = time.time()
cache()
p(f"# Data profile (generated by explore/profile.py, cache build + run {{T}}s)\n")

# 1. Row counts
p("## 1. Row counts\n")
rows = []
for ph in PHASES:
    for t in TABLES:
        f = f"{CACHE}/{ph}/{t}.parquet"
        if os.path.exists(f):
            n = con.execute(f"SELECT count(*) FROM '{f}'").fetchone()[0]
            rows.append(f"| {ph} | {t} | {n:,} |")
p("| phase | table | rows |\n|---|---|---|\n" + "\n".join(rows) + "\n")

# Side files counts
p("**Side files (number of files / rows) per phase**\n")
p("| phase | folder | files | rows |\n|---|---|---|---|")
for ph in PHASES:
    for d in ["direct_debit_batches", "card_settlements", "cheque_deposits", "payment_runs"]:
        path = f"{ROOT}/{ph}/{d}"
        if os.path.isdir(path):
            files = [x for x in os.listdir(path) if x.endswith(".csv")]
            n = con.execute(f"SELECT count(*) FROM read_csv('{path}/*.csv', union_by_name=true, all_varchar=true)").fetchone()[0] if files else 0
            p(f"| {ph} | {d} | {len(files)} | {n:,} |")
    for d in ["remittance_advices", "pdfs"]:
        path = f"{ROOT}/{ph}/{d}"
        if os.path.isdir(path):
            n = sum(len(fs) for _, _, fs in os.walk(path))
            p(f"| {ph} | {d} | {n:,} | (incl. index.csv) |")
p()

# 2. Schemas
p("## 2. Columns and types (train / live)\n")
for t in ["bank_transactions", "ar_invoices", "ap_invoices", "credit_notes", "golden_allocations"]:
    df = con.execute(f"DESCRIBE SELECT * FROM {view('train', t)}").df()
    p(f"- `{t}`: " + ", ".join(f"{r.column_name}:{r.column_type}" for r in df.itertuples()))
df = con.execute(f"DESCRIBE SELECT * FROM {view('live', 'open_items_at_start')}").df()
p("- `open_items_at_start` (live): " + ", ".join(f"{r.column_name}:{r.column_type}" for r in df.itertuples()))
p()

# 3. Bank line distributions
for ph in ["train", "live"]:
    bt = view(ph, "bank_transactions")
    p(f"## 3.{ph} Bank lines — {ph}\n")
    md(f"""SELECT statement_format, count(*) n, round(100*count(*)/sum(count(*)) over(),1) pct,
              round(100*avg((counterparty_name IS NOT NULL)::int),1) pct_cp_name,
              round(100*avg((orig_currency IS NOT NULL)::int),1) pct_orig_ccy
           FROM {bt} GROUP BY 1 ORDER BY 2 DESC""", "by statement format")
    md(f"""SELECT currency, count(*) n, sum((amount>0)::int) n_in, sum((amount<0)::int) n_out,
              sum((amount=0)::int) n_zero
           FROM {bt} GROUP BY 1 ORDER BY 2 DESC""", "by account currency / direction")
    md(f"""SELECT entity, count(*) n FROM {bt} GROUP BY 1 ORDER BY 2 DESC""", "by entity", 30)
    md(f"""SELECT min(booking_date) min_d, max(booking_date) max_d, count(DISTINCT account_id) accounts,
              count(*) - count(DISTINCT bank_txn_id) dup_ids,
              sum((text IS NULL OR text='')::int) empty_text,
              sum((value_date < booking_date - 7 OR value_date > booking_date + 7)::int) odd_value_date
           FROM {bt}""", "sanity")

# 4. Golden (train)
g = view("train", "golden_allocations")
bt = view("train", "bank_transactions")
p("## 4. Golden (TRAIN)\n")
md(f"""SELECT (SELECT count(DISTINCT bank_txn_id) FROM {g}) golden_lines,
          (SELECT count(*) FROM {bt}) bank_lines,
          (SELECT count(*) FROM {bt} b WHERE NOT EXISTS (SELECT 1 FROM {g} x WHERE x.bank_txn_id=b.bank_txn_id)) bank_lines_without_golden,
          (SELECT count(*) FROM {g} WHERE item_id IS NOT NULL) item_rows,
          (SELECT count(*) FROM {g} WHERE item_id IS NULL) no_item_rows""", "coverage")
md(f"""WITH k AS (SELECT bank_txn_id, count(item_id) n FROM {g} GROUP BY 1)
       SELECT CASE WHEN n=0 THEN '0' WHEN n=1 THEN '1' WHEN n<=5 THEN '2-5' WHEN n<=20 THEN '6-20'
                   WHEN n<=100 THEN '21-100' ELSE '>100' END bucket,
              count(*) lines, sum(n) pairs, max(n) max_items
       FROM k GROUP BY 1 ORDER BY min(n)""", "items per bank line")
md(f"""SELECT category, count(*) n FROM {g} WHERE item_id IS NULL GROUP BY 1 ORDER BY 2 DESC""",
   "no-item categories", 25)
md(f"""SELECT coalesce(exception,'(empty)') exception, count(*) rows,
              sum((item_id IS NULL)::int) no_item_rows FROM {g} GROUP BY 1 ORDER BY 2 DESC""", "exceptions")
md(f"""SELECT segment, count(DISTINCT bank_txn_id) lines, count(*) rows, round(avg(difficulty),2) avg_diff
       FROM {g} GROUP BY 1 ORDER BY 2 DESC""", "segments (by lines)", 60)
md(f"""SELECT left(item_id,3) prefix, count(*) rows FROM {g} WHERE item_id IS NOT NULL GROUP BY 1 ORDER BY 2 DESC""",
   "item types in golden")
md(f"""SELECT count(*) pairs_with_multiple_lines FROM (
         SELECT item_id FROM {g} WHERE item_id IS NOT NULL GROUP BY 1 HAVING count(DISTINCT bank_txn_id)>1)""",
   "items settled by more than one bank line (instalments, partials, returns, duplicates)")

# 5. Join keys
p("## 5. Join keys\n")
items_train = " UNION ALL ".join(
    [f"SELECT item_id, entity, currency, total_amount FROM {view('train', t)}" for t in ["ar_invoices", "ap_invoices", "credit_notes"]])
md(f"""WITH it AS ({items_train})
       SELECT count(*) golden_item_rows,
              sum((it.item_id IS NULL)::int) item_not_in_train_item_tables
       FROM {g} x LEFT JOIN it USING(item_id) WHERE x.item_id IS NOT NULL""",
   "golden item_id → train item tables")
md(f"""WITH it AS ({items_train})
       SELECT round(100*avg((b.currency <> it.currency)::int),2) pct_pairs_cross_currency,
              round(100*avg((b.entity <> it.entity)::int),2) pct_pairs_cross_entity
       FROM {g} x JOIN {bt} b USING(bank_txn_id) JOIN it USING(item_id)""",
   "bank line vs item: currency / entity mismatch (FX, payment factory)")
md(f"""WITH it AS (SELECT item_id, document_number d FROM {view('train','ar_invoices')}
                 UNION ALL SELECT item_id, supplier_invoice_number FROM {view('train','ap_invoices')}
                 UNION ALL SELECT item_id, document_number FROM {view('train','credit_notes')})
       SELECT round(100*avg((strpos(upper(coalesce(b.text,'')||' '||coalesce(b.remittance_info,'')||' '||coalesce(b.ref1,'')||' '||coalesce(b.ref2,'')), upper(it.d))>0)::int),1)
              pct_pairs_doc_number_verbatim_in_bank_text
       FROM {g} x JOIN {bt} b USING(bank_txn_id) JOIN it USING(item_id)""",
   "how often our printed document number appears verbatim in the bank text")

# 6. Normalised patterns
p("## 6. Unique text patterns (digits/IDs/dates stripped)\n")
NORM = r"""trim(regexp_replace(regexp_replace(regexp_replace(upper(strip_accents(coalesce(text,''))),
             '[A-Z]*[0-9][A-Z0-9/\-\.]*', '#', 'g'), '[^A-Z# ]', ' ', 'g'), ' +', ' ', 'g'))"""
for ph in ["train", "live"]:
    b = view(ph, "bank_transactions")
    md(f"""SELECT statement_format, (amount>0) is_credit, count(*) lines,
              count(DISTINCT {NORM}) patterns_full,
              count(DISTINCT left({NORM}, 20)) patterns_first20
           FROM {b} GROUP BY 1,2 ORDER BY 1,2""", f"{ph}: distinct normalised text patterns")
md(f"""WITH x AS (SELECT DISTINCT bank_txn_id, category FROM {g} WHERE item_id IS NULL)
       SELECT category, count(*) lines, count(DISTINCT {NORM}) patterns,
              count(DISTINCT left({NORM},20)) patterns_first20,
              count(DISTINCT bank_code) bank_codes
       FROM x JOIN {bt} USING(bank_txn_id) GROUP BY 1 ORDER BY 2 DESC""",
   "train no-item lines: patterns per category (→ LLM-per-pattern feasibility)", 25)
md(f"""WITH x AS (SELECT DISTINCT bank_txn_id, category FROM {g} WHERE item_id IS NULL),
            pat AS (SELECT left({NORM},20) pat, count(DISTINCT category) ncat, count(*) n
                    FROM x JOIN {bt} USING(bank_txn_id) GROUP BY 1)
       SELECT sum((ncat=1)::int) patterns_single_category, sum((ncat>1)::int) patterns_ambiguous,
              sum(CASE WHEN ncat>1 THEN n ELSE 0 END) lines_in_ambiguous_patterns FROM pat""",
   "are first-20-char patterns pure w.r.t. category?")
md(f"""SELECT {NORM} pattern, count(*) n FROM {view('live','bank_transactions')}
       GROUP BY 1 ORDER BY 2 DESC""", "live: top 25 normalised patterns", 25)

# 7. Weird things
p("## 7. Oddities checked\n")
md(f"""SELECT (SELECT count(*) FROM {view('live','open_items_at_start')}) live_open_items,
          (SELECT round(sum(open_amount)/1e6,1) FROM {view('live','open_items_at_start')}) live_open_amount_M,
          (SELECT count(*) FROM {view('live','open_items_at_start')} WHERE open_amount > total_amount + 0.01) open_gt_total,
          (SELECT count(*) FROM {view('live','open_items_at_start')} WHERE open_amount <= 0) open_le_0""",
   "live opening balances")
md(f"""SELECT left(item_id,3) prefix, count(*) n, min(issue_date) min_issue, max(issue_date) max_issue
       FROM {view('live','open_items_at_start')} GROUP BY 1 ORDER BY 1""", "live open items by type")
md(f"""SELECT account_id, statement_format, min(booking_date) first, max(booking_date) last, count(*) n
       FROM {view('live','bank_transactions')} WHERE bank='MONC' OR account_id LIKE '%MONC%'
       GROUP BY 1,2 ORDER BY 1,3""", "Banco del Moncayo N43 → camt switch in LIVE")

T = round(time.time() - t0)
text = "\n".join(out).replace("{T}", str(T))
open("explore/PROFILE.md", "w").write(text)
print(f"wrote explore/PROFILE.md in {T}s, {len(text):,} chars")
